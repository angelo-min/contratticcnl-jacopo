export function getCCNLBySlug(slug: string): CCNL | undefined {
  return ccnlData.find((c) => c.slug === slug)
}

export function getCCNLByMacrosettore(macrosettoreSlug: string): CCNL[] {
  return ccnlData.filter((c) => c.macrosettore === macrosettoreSlug)
}

export function getMacrosettoreBySlug(slug: string): Macrosettore | undefined {
  return macrosettori.find((m) => m.slug === slug)
}

export function searchCCNL(query: string): CCNL[] {
  const lowerQuery = query.toLowerCase()
  return ccnlData.filter(
    (c) =>
      c.nome.toLowerCase().includes(lowerQuery) ||
      c.settore.toLowerCase().includes(lowerQuery) ||
      c.macrosettore.toLowerCase().includes(lowerQuery) ||
      c.descrizione.toLowerCase().includes(lowerQuery)
  )
}

export function getCCNLWithTabelle(): CCNL[] {
  return ccnlData.filter(
    (c) => c.tabelleRetributive && c.tabelleRetributive.length > 0
  )
}

export function getLatestUpdates(count: number = 5): CCNL[] {
  return [...ccnlData]
    .sort((a, b) => new Date(b.dataFirma).getTime() - new Date(a.dataFirma).getTime())
    .slice(0, count)
}
